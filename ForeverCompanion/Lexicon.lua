local function normalizeWord(text)
    text = tostring(text or ""):lower()
    text = text:gsub("^%s+", ""):gsub("%s+$", "")
    text = text:gsub("[%p]+$", "")
    return text
end

function FC:BuildLexiconIndex()
    if self.lexiconIndex then return self.lexiconIndex end
    self.lexiconIndex = {}
    for _, entry in ipairs(self.lexicon or {}) do
        self.lexiconIndex[normalizeWord(entry.word)] = entry
    end
    return self.lexiconIndex
end

function FC:GetLexiconEntry(word)
    local key = normalizeWord(word)
    if key == "" then return nil end
    return self:BuildLexiconIndex()[key]
end

function FC:EnsureVocabularyMemory()
    self.db.sharedMemory = self.db.sharedMemory or {}
    self.db.sharedMemory.vocabulary = self.db.sharedMemory.vocabulary or { seen = {}, correct = 0, wrong = 0 }
    local v = self.db.sharedMemory.vocabulary
    v.seen = v.seen or {}
    v.correct = tonumber(v.correct) or 0
    v.wrong = tonumber(v.wrong) or 0
    return v
end

function FC:PickVocabularyEntry(preferUnseen)
    local bank = self.lexicon or {}
    if #bank == 0 then return nil end
    local memory = self:EnsureVocabularyMemory()
    if preferUnseen then
        local unseen = {}
        for _, entry in ipairs(bank) do
            if not memory.seen[normalizeWord(entry.word)] then unseen[#unseen + 1] = entry end
        end
        if #unseen > 0 then return unseen[math.random(1, #unseen)] end
    end
    return bank[math.random(1, #bank)]
end

function FC:TellVocabularyWord(requested)
    local entry
    if requested and requested ~= "" then
        entry = self:GetLexiconEntry(requested)
        if not entry then
            local key = normalizeWord(requested)
            local matches = {}
            for _, candidate in ipairs(self.lexicon or {}) do
                if normalizeWord(candidate.word):find(key, 1, true) == 1 then
                    matches[#matches + 1] = candidate.word
                    if #matches >= 6 then break end
                end
            end
            if #matches > 0 then
                self:Debug("No exact dictionary entry for '" .. tostring(requested) .. "'. Nearby: " .. table.concat(matches, ", "))
            else
                self:Debug("No built-in dictionary entry for '" .. tostring(requested) .. "'.")
            end
            return false
        end
    else
        entry = self:PickVocabularyEntry(true)
    end
    if not entry then return false end
    local memory = self:EnsureVocabularyMemory()
    local key = normalizeWord(entry.word)
    memory.seen[key] = (tonumber(memory.seen[key]) or 0) + 1
    local intros = {
        "Vocabulary break: ", "Word for the road: ", "Tiny dictionary moment: ", "Vexa vocabulary: ",
        "Useful word: ", "Put this one in your pocket: ", "Language snack: ", "Word worth stealing: ",
    }
    local text = intros[math.random(1, #intros)] .. entry.word .. " (" .. entry.pos .. ") — " .. entry.definition .. "."
    self:Say(text, "talk", 100, true, { topic = "vocabulary", category = "learning", reason = "vocabulary builder" })
    self.state.lastVocabularyWord = entry.word
    return true
end

local function shuffle(list)
    for i = #list, 2, -1 do
        local j = math.random(1, i)
        list[i], list[j] = list[j], list[i]
    end
end

function FC:StartVocabularyQuiz(force)
    if self.state.pendingVocabularyQuiz and not force then return false end
    local target = self:PickVocabularyEntry(false)
    if not target then return false end
    local options = { { text = target.word, correct = true } }
    local used = { [normalizeWord(target.word)] = true }
    local guard = 0
    while #options < 4 and guard < 100 do
        guard = guard + 1
        local other = self:PickVocabularyEntry(false)
        local key = other and normalizeWord(other.word) or nil
        if other and key and not used[key] then
            used[key] = true
            options[#options + 1] = { text = other.word, correct = false }
        end
    end
    if #options < 4 then return false end
    shuffle(options)
    local answer
    local parts = {}
    for i, opt in ipairs(options) do
        if opt.correct then answer = i end
        parts[#parts + 1] = tostring(i) .. ") " .. opt.text
    end
    self.state.pendingVocabularyQuiz = { word = target.word, answer = answer, options = options, askedAt = GetTime(), answerAt = GetTime() + 35 }
    local text = "Vocabulary check: which word means '" .. target.definition .. "'? " .. table.concat(parts, "   ") .. "   /fc vocabanswer 1-4"
    self:Say(text, "talk", 100, true, { topic = "vocabquiz", category = "learning", reason = "vocabulary quiz" })
    return true
end

function FC:AnswerVocabularyQuiz(value, automatic)
    local q = self.state.pendingVocabularyQuiz
    if not q then
        if not automatic then self:Debug("No vocabulary quiz is waiting for an answer.") end
        return false
    end
    local n = tonumber(value)
    if not n then
        self:Debug("Use /fc vocabanswer 1, 2, 3, or 4.")
        return false
    end
    local opt = q.options and q.options[n]
    if not opt then
        self:Debug("That answer must be 1, 2, 3, or 4.")
        return false
    end
    local memory = self:EnsureVocabularyMemory()
    local target = self:GetLexiconEntry(q.word)
    if opt.correct then
        memory.correct = memory.correct + 1
        self:Say("Correct. '" .. q.word .. "' means " .. (target and target.definition or "that definition") .. ". Look at you being dangerously literate.", "happy", 100, true, { topic = "vocabquiz", category = "learning", reason = "correct vocabulary answer" })
    else
        memory.wrong = memory.wrong + 1
        self:Say("Not quite. The answer was '" .. q.word .. "' — " .. (target and target.definition or "the target definition") .. ". I will absolutely ask again later.", "shrug", 100, true, { topic = "vocabquiz", category = "learning", reason = "incorrect vocabulary answer" })
    end
    self.state.pendingVocabularyQuiz = nil
    return opt.correct
end


function FC:VocabularyTick()
    local q = self.state.pendingVocabularyQuiz
    if not q or GetTime() < (q.answerAt or math.huge) then return end
    if self.state.inCombat or self.state.contextMode == "combat" then return end
    local target = self:GetLexiconEntry(q.word)
    self.state.pendingVocabularyQuiz = nil
    self:QueueSay("Vocabulary answer: '" .. tostring(q.word) .. "' — " .. (target and target.definition or "the correct choice") .. ".", "playful", 25, 0, "vocabquizanswer", true, nil, { topic = "vocabquizanswer", category = "learning", reason = "delayed vocabulary answer" })
end

function FC:TellWordRoot()
    local roots = self.wordRoots or {}
    if #roots == 0 then return false end
    local r = roots[math.random(1, #roots)]
    local intros = { "Word-root break: ", "Language anatomy: ", "Root of the moment: ", "Vocabulary cheat code: " }
    self:Say(intros[math.random(1, #intros)] .. r.root .. " means " .. r.meaning .. ". Examples: " .. r.examples .. ".", "talk", 100, true, { topic = "wordroot", category = "learning", reason = "word root" })
    return true
end

function FC:VocabularySummary()
    local memory = self:EnsureVocabularyMemory()
    local seen = 0
    for _ in pairs(memory.seen or {}) do seen = seen + 1 end
    return string.format("%d dictionary entries, %d word roots, %d words seen, quiz score %d correct / %d wrong", #(self.lexicon or {}), #(self.wordRoots or {}), seen, memory.correct or 0, memory.wrong or 0)
end
